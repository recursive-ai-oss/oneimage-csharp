#!/usr/bin/env python3
"""Extracts the constant tables of RFC 6386 (VP8) into src/OneImage/Codecs/WebP/VP8Tables.cs.

Usage: gen_vp8_tables.py rfc6386.txt > VP8Tables.cs
"""
import re
import sys

text = open(sys.argv[1], encoding='utf-8').read().split('\n')
clean = []
for l in text:
    if l.startswith('Bankoski, et al.') or l.startswith('RFC 6386 ') or '\f' in l:
        continue
    clean.append(l)
body = '\n'.join(clean)
body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)


def grab(decl, expect):
    # find declaration followed by data (the one with '= {')
    for m in re.finditer(re.escape(decl) + r'[^;=]*=\s*\{', body):
        start = m.end() - 1
        depth = 0
        i = start
        while True:
            c = body[i]
            if c == '{':
                depth += 1
            elif c == '}':
                depth -= 1
                if depth == 0:
                    break
            i += 1
        nums = [int(x) for x in re.findall(r'\b\d+\b', body[start:i + 1])]
        if len(nums) == expect:
            return nums
    raise SystemExit('table not found: ' + decl)


def emit(name, nums, doc, ty='byte'):
    out = ['    /// <summary>' + doc + '</summary>', '    internal static ReadOnlySpan<' + ty + '> ' + name + ' =>', '    [']
    for i in range(0, len(nums), 16):
        out.append('        ' + ', '.join(str(n) for n in nums[i:i + 16]) + ',')
    out.append('    ];')
    out.append('')
    return '\n'.join(out)


print('// <auto-generated> by tools/gen_vp8_tables.py from the tables of RFC 6386. </auto-generated>')
print('namespace OneImage.Codecs.WebP;')
print()
print('/// <summary>Constant probability and quantizer tables of the VP8 format (RFC 6386).</summary>')
print('internal static class VP8Tables')
print('{')
print(emit('KeyFrameBModeProbs', grab('kf_bmode_prob', 900), 'Sub-block mode probabilities [above][left][9] (RFC 6386 section 11.5).'))
print(emit('CoeffUpdateProbs', grab('coeff_update_probs', 1056), 'Probabilities that a coefficient probability is updated in the frame header [4][8][3][11] (section 13.4).'))
print(emit('DefaultCoeffProbs', grab('default_coeff_probs', 1056), 'Default coefficient probabilities [4][8][3][11] (section 13.5).'))
print(emit('DcQLookup', grab('dc_qlookup', 128), 'DC quantizer step by index (section 14.1).', 'ushort'))
print(emit('AcQLookup', grab('ac_qlookup', 128), 'AC quantizer step by index (section 14.1).', 'ushort'))
print('}')
