#!/usr/bin/env python3
"""Generates src/OneImage.Text/Unicode/VerticalOrientationData.g.cs from VerticalOrientation.txt (UAX #50).

Usage: gen_vertical_orientation.py [--version 17.0.0] [--cache DIR]

Downloads the file into --cache (default: ./ucd-cache, never committed) and writes the Vertical_Orientation property as
sorted, merged ranges: R (rotated), U (upright), Tr (rotated unless the font has a vertical form) and Tu (upright unless
the font has no vertical form). Code points not listed are R.

The Unicode data files are (c) Unicode, Inc. and used under the Unicode License v3 (see THIRD-PARTY-NOTICES.md).
"""
import argparse
import os
import sys
import urllib.request

VALUES = {"R": 0, "U": 1, "Tr": 2, "Tu": 3}


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", default="17.0.0")
    ap.add_argument("--cache", default=os.path.join(os.getcwd(), "ucd-cache"))
    ap.add_argument("--out", default=os.path.join(root, "src", "OneImage.Text", "Unicode", "VerticalOrientationData.g.cs"))
    a = ap.parse_args()
    os.makedirs(a.cache, exist_ok=True)
    path = os.path.join(a.cache, "VerticalOrientation.txt")
    if not os.path.exists(path):
        url = f"https://www.unicode.org/Public/{a.version}/ucd/VerticalOrientation.txt"
        print("fetching", url, file=sys.stderr)
        urllib.request.urlretrieve(url, path)

    rows = []
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        rng, val = [p.strip() for p in line.split(";")]
        lo, _, hi = rng.partition("..")
        rows.append((int(lo, 16), int(hi or lo, 16), VALUES[val]))
    rows.sort()
    merged = []
    for lo, hi, v in rows:
        if merged and merged[-1][1] + 1 == lo and merged[-1][2] == v:
            merged[-1] = (merged[-1][0], hi, v)
        else:
            merged.append((lo, hi, v))
    # Rotated is the default, so runs of R are not stored.
    merged = [m for m in merged if m[2] != 0]

    def span(name, vals, doc):
        out = [f"    /// <summary>{doc}</summary>", f"    internal static ReadOnlySpan<int> {name} =>", "    ["]
        for i in range(0, len(vals), 12):
            out.append("        " + ", ".join(str(v) for v in vals[i:i + 12]) + ",")
        out.append("    ];")
        return "\n".join(out)

    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// <auto-generated>\n")
        f.write(f"// Generated by tools/gen_vertical_orientation.py from VerticalOrientation.txt of the Unicode Character Database {a.version}. Do not edit.\n")
        f.write("// Unicode data files are Copyright (c) Unicode, Inc. and used under the Unicode License v3 (THIRD-PARTY-NOTICES.md).\n")
        f.write("// </auto-generated>\nnamespace OneImage.Text.Unicode;\n\n")
        f.write("/// <summary>Vertical_Orientation ranges (UAX #50) for everything that is not rotated (R).</summary>\n")
        f.write("internal static class VerticalOrientationData\n{\n")
        f.write(span("First", [m[0] for m in merged], "First code point of each range.") + "\n\n")
        f.write(span("Last", [m[1] for m in merged], "Last code point of each range.") + "\n\n")
        f.write(span("Value", [m[2] for m in merged], "0 R, 1 U, 2 Tr, 3 Tu.") + "\n")
        f.write("}\n")
    print(f"vertical orientation: {len(merged)} ranges", file=sys.stderr)


main()
