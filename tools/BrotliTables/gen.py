#!/usr/bin/env python3
"""Regenerates the Brotli static tables from the text of RFC 7932.

Usage: gen.py rfc7932.txt <repo>/src/OneImage.Text/Compression

Writes brotli-dictionary.bin (RFC 7932 Appendix A, 122,784 bytes, CRC-32 0x5136cb04) and BrotliTables.cs
(the word transforms of Appendix B and the context lookup tables of section 7.1).
"""
import re
import sys
import zlib

src, out = sys.argv[1], sys.argv[2]
lines = [l for l in open(src, encoding="utf8").read().split("\n") if l.strip() and not l.startswith(("Alakuijala", "RFC 7932  "))]

# Appendix A: the dictionary as hex, 32 bytes per line.
a = next(i for i, l in enumerate(lines) if l.startswith("Appendix A.  Static"))
b = next(i for i, l in enumerate(lines) if l.startswith("Appendix B.  List"))
hexs = "".join(m.group(1) for l in lines[a:b] if (m := re.fullmatch(r"      ([0-9a-f]{64})", l)))
data = bytes.fromhex(hexs)
assert len(data) == 122784 and zlib.crc32(data) == 0x5136CB04
open(out + "/brotli-dictionary.bin", "wb").write(data)

# Appendix B: id, prefix, transform, suffix.
trs = []
for l in lines[b:b + 260]:
    m = re.fullmatch(r'\s+(\d+)\s+"((?:[^"\\]|\\.)*)"\s+(\w+)\s+"((?:[^"\\]|\\.)*)"', l)
    if m:
        trs.append(m.groups())
assert [int(t[0]) for t in trs] == list(range(121))


def cstr(s):
    r = bytearray()
    i = 0
    while i < len(s):
        if s[i] == "\\":
            c = s[i + 1]
            if c == "x":
                r.append(int(s[i + 2:i + 4], 16))
                i += 4
                continue
            r.append({"n": 10, "t": 9, '"': 34}[c])
            i += 2
        else:
            r.append(ord(s[i]))
            i += 1
    return bytes(r)


def kind(n):
    if n == "Identity":
        return 0
    if n == "FermentFirst":
        return 1
    if n == "FermentAll":
        return 2
    if n.startswith("OmitFirst"):
        return 2 + int(n[9:])      # 3..11
    return 11 + int(n[8:])         # OmitLast1..9 = 12..20


# The RFC's check value: prefix 0, kind byte, suffix 0 for each transform.
chk = b"".join(cstr(t[1]) + b"\0" + bytes([kind(t[2])]) + cstr(t[3]) + b"\0" for t in trs)
assert len(chk) == 648 and zlib.crc32(chk) == 0x3D965F81

# Section 7.1 lookup tables.
def table(name):
    i = next(i for i, l in enumerate(lines) if l.strip() == name + " :=")
    vals = []
    for l in lines[i + 1:i + 40]:
        if re.fullmatch(r"\s+[\d, ]+,?\s*", l):
            vals += [int(x) for x in re.findall(r"\d+", l)]
        elif vals and l.strip():
            break
    assert len(vals) == 256, (name, len(vals))
    return vals


luts = {n: table(n) for n in ("Lut0", "Lut1", "Lut2")}
for n, crc in (("Lut0", 0x8E91EFB7), ("Lut1", 0xD01A32F4), ("Lut2", 0x0DD7A0D6)):
    assert zlib.crc32(bytes(luts[n])) == crc, n


def arr(vals):
    return ", ".join(str(v) for v in vals)


w = []
w.append("// <auto-generated>Generated by tools/BrotliTables/gen.py from RFC 7932; do not edit.</auto-generated>")
w.append("namespace OneImage.Text.Compression;")
w.append("")
w.append("internal static class BrotliTables")
w.append("{")
w.append("    /// <summary>Context lookup tables of RFC 7932 section 7.1.</summary>")
for n in ("Lut0", "Lut1", "Lut2"):
    rows = [arr(luts[n][i:i + 16]) for i in range(0, 256, 16)]
    w.append(f"    public static ReadOnlySpan<byte> {n} => [")
    w.append("        " + ",\n        ".join(rows) + "];")
    w.append("")
w.append("    /// <summary>The 121 word transforms of RFC 7932 Appendix B: prefix, kind (0 identity, 1 ferment first, 2 ferment all, 3..11 omit first 1..9, 12..20 omit last 1..9), suffix.</summary>")
w.append("    public static readonly (byte[] Prefix, byte Kind, byte[] Suffix)[] Transforms =")
w.append("    [")
for t in trs:
    p = ", ".join(str(x) for x in cstr(t[1]))
    s = ", ".join(str(x) for x in cstr(t[3]))
    w.append(f"        ([{p}], {kind(t[2])}, [{s}]),")
w.append("    ];")
w.append("}")
open(out + "/BrotliTables.cs", "w", encoding="utf8", newline="\n").write("\n".join(w) + "\n")
print("ok", len(trs))
