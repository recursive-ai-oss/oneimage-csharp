    private static Rgba32[] Unpack(uint[] packed)
    {
        var r = new Rgba32[packed.Length];
        for (int i = 0; i < r.Length; i++)
        {
            uint v = packed[i];
            r[i] = new Rgba32((byte)(v >> 24), (byte)(v >> 16), (byte)(v >> 8), (byte)v);
        }

        return r;
    }
